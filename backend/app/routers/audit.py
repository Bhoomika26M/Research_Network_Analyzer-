import csv
import io
from datetime import datetime
from typing import List, Optional
from fastapi import APIRouter, Depends, Query, HTTPException, Response
from fastapi.responses import StreamingResponse
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select, and_, or_, desc
from app.database import get_db
from app.models import AuditLog, ComplianceReport, User
from app.schemas import (
    AuditLogRead, AuditLogCreate,
    ComplianceReportRead, ComplianceReportCreate, ComplianceReportGenerateRequest
)
from app.auth import get_current_user

router = APIRouter(prefix="/api", tags=["Audit Logs & Compliance"])

@router.get("/audit-logs", response_model=List[AuditLogRead])
async def get_audit_logs(
    tab: Optional[str] = Query(None, description="Active tab: User Activity, Publication History, Project Logs, Security Logs"),
    date_from: Optional[str] = Query(None, description="YYYY-MM-DD"),
    date_to: Optional[str] = Query(None, description="YYYY-MM-DD"),
    user: Optional[str] = Query(None, description="Filter by username or email"),
    action: Optional[str] = Query(None, description="Filter by action name"),
    limit: int = Query(100, ge=1, le=1000),
    offset: int = Query(0, ge=0),
    db: AsyncSession = Depends(get_db)
):
    """Retrieve audit logs with tab and field filters."""
    query = select(AuditLog)
    filters = []

    if tab == "Security Logs":
        filters.append(or_(AuditLog.result == "Failed", AuditLog.action.ilike("%Login%")))
    elif tab and tab != "All":
        # match tab category or default
        filters.append(AuditLog.tab_category == tab)

    if date_from:
        filters.append(AuditLog.timestamp >= f"{date_from} 00:00:00")
    if date_to:
        filters.append(AuditLog.timestamp <= f"{date_to} 23:59:59")
    if user:
        filters.append(AuditLog.user.ilike(f"%{user}%"))
    if action and action != "All Action Types":
        filters.append(AuditLog.action.ilike(f"%{action}%"))

    if filters:
        query = query.where(and_(*filters))

    query = query.order_by(desc(AuditLog.timestamp), desc(AuditLog.id)).offset(offset).limit(limit)
    result = await db.execute(query)
    return result.scalars().all()

@router.post("/audit-logs", response_model=AuditLogRead)
async def create_audit_log(
    log_in: AuditLogCreate,
    db: AsyncSession = Depends(get_db)
):
    """Create a new audit log entry."""
    now_str = log_in.timestamp or datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S")
    log = AuditLog(
        timestamp=now_str,
        user=log_in.user,
        action=log_in.action,
        target=log_in.target,
        ip=log_in.ip,
        result=log_in.result,
        tab_category=log_in.tab_category or "User Activity"
    )
    db.add(log)
    await db.commit()
    await db.refresh(log)
    return log

@router.get("/audit-logs/export")
async def export_audit_logs_csv(
    tab: Optional[str] = Query(None),
    date_from: Optional[str] = Query(None),
    date_to: Optional[str] = Query(None),
    user: Optional[str] = Query(None),
    action: Optional[str] = Query(None),
    db: AsyncSession = Depends(get_db)
):
    """Export filtered audit logs as downloadable CSV."""
    logs = await get_audit_logs(tab, date_from, date_to, user, action, limit=5000, offset=0, db=db)
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["Timestamp", "User", "Action", "Target Record", "IP / Device", "Result"])
    for l in logs:
        writer.writerow([l.timestamp, l.user, l.action, l.target, l.ip, l.result])

    content = output.getvalue()
    filename = f"audit_log_export_{datetime.utcnow().strftime('%Y-%m-%d')}.csv"
    return Response(
        content=content,
        media_type="text/csv",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'}
    )

@router.get("/compliance-reports", response_model=List[ComplianceReportRead])
async def get_compliance_reports(db: AsyncSession = Depends(get_db)):
    """Retrieve all generated compliance reports."""
    query = select(ComplianceReport).order_by(desc(ComplianceReport.created_at))
    result = await db.execute(query)
    return result.scalars().all()

@router.post("/compliance-reports/generate", response_model=ComplianceReportRead)
async def generate_compliance_report(
    req: ComplianceReportGenerateRequest,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """Generate a new compliance audit report from current logs."""
    query = select(AuditLog).order_by(desc(AuditLog.timestamp)).limit(500)
    result = await db.execute(query)
    logs = result.scalars().all()

    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["Report Name", req.name])
    writer.writerow(["Range", req.range])
    writer.writerow(["Generated By", req.by or current_user.email])
    writer.writerow(["Generated At", datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S")])
    writer.writerow([])
    writer.writerow(["Timestamp", "User", "Action", "Target Record", "IP / Device", "Result"])
    for l in logs:
        writer.writerow([l.timestamp, l.user, l.action, l.target, l.ip, l.result])

    csv_text = output.getvalue()
    size_bytes = len(csv_text.encode("utf-8"))
    size_str = f"{size_bytes / 1024:.1f} KB" if size_bytes < 1024 * 1024 else f"{size_bytes / (1024 * 1024):.1f} MB"
    
    clean_name = req.name.lower().replace(" ", "_").replace("/", "_").replace("-", "_")
    filename = req.filename or f"{clean_name}_{datetime.utcnow().strftime('%Y%m%d')}.csv"

    report = ComplianceReport(
        name=req.name,
        range=req.range,
        by=req.by or current_user.email,
        date=datetime.utcnow().strftime("%Y-%m-%d"),
        size=size_str,
        csv_content=csv_text,
        filename=filename
    )
    db.add(report)

    # Log this action into audit logs!
    audit_entry = AuditLog(
        timestamp=datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S"),
        user=current_user.full_name or current_user.email,
        action="Report Exported",
        target=f"Compliance Report: {req.name}",
        ip="127.0.0.1",
        result="Success",
        tab_category="User Activity"
    )
    db.add(audit_entry)

    await db.commit()
    await db.refresh(report)
    return report

@router.get("/compliance-reports/{report_id}/download")
async def download_compliance_report(report_id: int, db: AsyncSession = Depends(get_db)):
    """Download the raw CSV file for a specific compliance report."""
    result = await db.execute(select(ComplianceReport).where(ComplianceReport.id == report_id))
    report = result.scalar_one_or_none()
    if not report:
        raise HTTPException(status_code=404, detail="Compliance report not found")

    return Response(
        content=report.csv_content,
        media_type="text/csv",
        headers={"Content-Disposition": f'attachment; filename="{report.filename}"'}
    )
